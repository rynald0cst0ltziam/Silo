<?php
/**
 * Settings, connection credentials and the edge config consumed by the drop-in.
 *
 * @package silo-connector
 */

defined( 'ABSPATH' ) || exit;

/**
 * Central access to every option the connector stores.
 */
class Silo_Settings {

	const OPTION = 'silo_settings';

	/**
	 * Local toggles. Invalidation itself is not optional: it is what keeps stock honest.
	 */
	public static function defaults(): array {
		return array(
			'page_cache'         => true,
			'store_api_cache'    => true,
			'warmup'             => true,
			'cache_front_page'   => false,
			'warmup_concurrency' => 4,
		);
	}

	public static function all(): array {
		$stored = get_option( self::OPTION, array() );
		return wp_parse_args( is_array( $stored ) ? $stored : array(), self::defaults() );
	}

	/**
	 * @return mixed
	 */
	public static function get( string $key ) {
		$all = self::all();
		return $all[ $key ] ?? null;
	}

	public static function update( array $changes ): array {
		$current = self::all();
		foreach ( array( 'page_cache', 'store_api_cache', 'warmup', 'cache_front_page' ) as $flag ) {
			if ( array_key_exists( $flag, $changes ) ) {
				$current[ $flag ] = (bool) filter_var( $changes[ $flag ], FILTER_VALIDATE_BOOLEAN );
			}
		}
		if ( array_key_exists( 'warmup_concurrency', $changes ) ) {
			$current['warmup_concurrency'] = max( 1, min( 8, absint( $changes['warmup_concurrency'] ) ) );
		}
		update_option( self::OPTION, $current, false );
		self::write_edge_config();
		return $current;
	}

	public static function api_key(): string {
		return (string) get_option( 'silo_api_key', '' );
	}

	public static function key_id(): string {
		$key = self::api_key();
		return '' === $key ? '' : hash( 'sha256', $key );
	}

	/**
	 * SaaS origin: explicit option, else the origin baked into the downloaded ZIP.
	 */
	public static function saas_url(): string {
		$url = (string) get_option( 'silo_saas_url', '' );
		if ( '' === $url ) {
			$url = self::build_value( 'saas_url' );
		}
		return untrailingslashit( esc_url_raw( $url ) );
	}

	/**
	 * Values injected into silo-build.php when the ZIP is generated by the Silo dashboard.
	 */
	public static function build_value( string $key ): string {
		static $build = null;
		if ( null === $build ) {
			$file  = SILO_DIR . 'silo-build.php';
			$build = is_readable( $file ) ? (array) include $file : array();
		}
		return isset( $build[ $key ] ) ? (string) $build[ $key ] : '';
	}

	public static function is_connected(): bool {
		return '' !== self::api_key() && '' !== self::saas_url() && (bool) get_option( 'silo_store', false );
	}

	/**
	 * Store identity returned by the handshake: id, name, url, tier, dashboard link.
	 */
	public static function store(): array {
		$store = get_option( 'silo_store', array() );
		return is_array( $store ) ? $store : array();
	}

	/**
	 * Config generated by Silo from the catalog scan.
	 */
	public static function remote_config(): array {
		$config = get_option( 'silo_config', array() );
		return is_array( $config ) ? $config : array();
	}

	public static function apply_remote_config( array $config ): bool {
		$current = self::remote_config();
		if ( ! empty( $current['version'] ) && (int) ( $config['version'] ?? 0 ) < (int) $current['version'] ) {
			return false;
		}
		update_option( 'silo_config', $config, false );
		self::write_edge_config();
		return true;
	}

	/**
	 * Secret that lets connector warmup requests regenerate pages. Never leaves the store.
	 */
	public static function warm_token(): string {
		$token = (string) get_option( 'silo_warm_token', '' );
		if ( '' === $token ) {
			$token = wp_generate_password( 40, false, false );
			update_option( 'silo_warm_token', $token, false );
		}
		return $token;
	}

	public static function site_host(): string {
		$parts = wp_parse_url( home_url() );
		return (string) ( $parts['host'] ?? '' ) . ( isset( $parts['port'] ) ? ':' . $parts['port'] : '' );
	}

	public static function site_dir(): string {
		return silo_site_dir( self::site_host() );
	}

	/**
	 * Paths of pages that depend on the shopper. These are never cached.
	 */
	public static function exclude_paths(): array {
		$paths = array( '/cart', '/checkout', '/my-account' );
		if ( function_exists( 'wc_get_page_id' ) ) {
			foreach ( array( 'cart', 'checkout', 'myaccount' ) as $page ) {
				$id = wc_get_page_id( $page );
				if ( $id > 0 ) {
					$path = wp_parse_url( (string) get_permalink( $id ), PHP_URL_PATH );
					if ( is_string( $path ) && '' !== trim( $path, '/' ) ) {
						$paths[] = untrailingslashit( $path );
					}
				}
			}
		}
		$remote = self::remote_config();
		foreach ( (array) ( $remote['exclusions'] ?? array() ) as $exclusion ) {
			if ( is_string( $exclusion ) && str_starts_with( $exclusion, '/' ) ) {
				$paths[] = $exclusion;
			}
		}
		return array_values( array_unique( $paths ) );
	}

	/**
	 * Write the small JSON file the drop-in reads on every request (no database access there).
	 */
	public static function write_edge_config(): void {
		$dir = self::site_dir();
		if ( ! wp_mkdir_p( $dir ) ) {
			return;
		}

		$settings = self::all();
		$remote   = self::remote_config();
		$variants = (array) ( $remote['variants'] ?? array() );
		$ttl      = (array) ( $remote['ttl'] ?? array() );

		$config = array(
			'enabled'       => self::is_connected() && ! empty( $settings['page_cache'] ),
			'warm_token'    => self::warm_token(),
			'variants'      => array(
				'currency'        => ! empty( $variants['currency'] ),
				'language_cookie' => ! empty( $variants['language_cookie'] ),
				'country'         => ! empty( $variants['country'] ),
			),
			'exclude_paths' => self::exclude_paths(),
			'ttl'           => array(
				'product'   => max( 60, (int) ( $ttl['product'] ?? 3600 ) ),
				'category'  => max( 60, (int) ( $ttl['category'] ?? 1800 ) ),
				'shop'      => max( 60, (int) ( $ttl['shop'] ?? 1800 ) ),
				'store_api' => max( 30, (int) ( $ttl['store_api'] ?? 300 ) ),
			),
			'store_api'     => self::is_connected() && ! empty( $settings['store_api_cache'] ),
			'front_page'    => ! empty( $settings['cache_front_page'] ),
			'version'       => (int) ( $remote['version'] ?? 0 ),
			'written'       => time(),
		);

		$tmp = $dir . 'config.json.' . wp_generate_password( 6, false, false );
		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents
		if ( false !== file_put_contents( $tmp, (string) wp_json_encode( $config ) ) ) {
			// phpcs:ignore WordPress.WP.AlternativeFunctions.rename_rename
			rename( $tmp, $dir . 'config.json' );
		}
	}

	/**
	 * Forget the connection. Cached pages are purged because nothing can invalidate them anymore.
	 */
	public static function disconnect(): void {
		foreach ( array( 'silo_api_key', 'silo_store', 'silo_config', 'silo_hb_last', 'silo_hb_ok', 'silo_hb_error', 'silo_auth_error' ) as $option ) {
			delete_option( $option );
		}
		Silo_Scanner::reset();
		self::write_edge_config();
		Silo_Page_Cache::purge_everything( true );
	}
}
