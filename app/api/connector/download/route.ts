import { promises as fs } from "fs";
import path from "path";
import { buildZip, type ZipEntry } from "@/lib/zip";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

const PLUGIN_DIR = path.join(process.cwd(), "silo-connector");
const SKIP = /(^|\/)(\.[^/]+|node_modules|silo-build\.php)(\/|$)/;

async function collect(dir: string, base = ""): Promise<ZipEntry[]> {
  const entries: ZipEntry[] = [];
  const items = await fs.readdir(dir, { withFileTypes: true });
  items.sort((a, b) => a.name.localeCompare(b.name));
  for (const item of items) {
    const rel = base ? `${base}/${item.name}` : item.name;
    if (SKIP.test(rel)) continue;
    const full = path.join(dir, item.name);
    if (item.isDirectory()) {
      entries.push({ path: `silo-connector/${rel}/`, data: Buffer.alloc(0) });
      entries.push(...(await collect(full, rel)));
    } else if (item.isFile()) {
      entries.push({ path: `silo-connector/${rel}`, data: await fs.readFile(full) });
    }
  }
  return entries;
}

/**
 * The connector ZIP, built on request so it always matches the deployed code and
 * already knows which Silo instance to talk to.
 */
export async function GET(req: Request) {
  const origin = new URL(req.url).origin;
  const saasUrl = (process.env.SILO_PUBLIC_URL || origin).replace(/\/+$/, "");

  const files = await collect(PLUGIN_DIR);
  const build = `<?php\n/**\n * Generated by Silo when this ZIP was downloaded.\n *\n * @package silo-connector\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nreturn array(\n\t'saas_url' => ${JSON.stringify(saasUrl).replace(/'/g, "\\'")},\n\t'built_at' => '${new Date().toISOString()}',\n);\n`;
  files.push({ path: "silo-connector/silo-build.php", data: Buffer.from(build, "utf8") });

  const zip = buildZip([{ path: "silo-connector/", data: Buffer.alloc(0) }, ...files]);

  return new Response(new Uint8Array(zip), {
    headers: {
      "Content-Type": "application/zip",
      "Content-Disposition": 'attachment; filename="silo-connector.zip"',
      "Content-Length": String(zip.length),
      "Cache-Control": "no-store",
    },
  });
}
